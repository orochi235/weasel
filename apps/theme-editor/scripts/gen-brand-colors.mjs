/**
 * Generate the LEGO and Copic swatch sets from their upstream sources.
 *
 * Both are fetched rather than transcribed, so a wrong hex would have to be
 * wrong upstream. Re-run when either source moves:
 *
 *   node apps/theme-editor/scripts/gen-brand-colors.mjs
 *
 * LEGO  — brickset.com/colours/status-Current, which is the piece LDraw's
 *         LDConfig has no field for: what LEGO is currently producing.
 * Copic — github.com/meodai/copic-colors (MIT), whose values are sampled from
 *         the swatch images on copic.jp rather than someone's idealisation.
 */
import { writeFileSync } from 'node:fs';

const UA = { 'user-agent': 'Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)' };
const hex2 = (n) => Number(n).toString(16).padStart(2, '0');

/** sRGB hex to OKLab, so "how colourful is this" is one number. */
function oklab(hex) {
  const [r, g, b] = [1, 3, 5]
    .map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((u) => (u <= 0.04045 ? u / 12.92 : ((u + 0.055) / 1.055) ** 2.4));
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return [
    0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  ];
}

/**
 * Near-neutral, by chroma rather than channel spread.
 *
 * Spread gets this wrong at the ends: LEGO's Black is a blue-black whose
 * channels differ by 25 while its chroma is under 0.02, so a spread test keeps
 * it. A categorical palette wants hues; neutrals are the theme ramp's job.
 */
function isNeutral(hex) {
  const [L, a, b] = oklab(hex);
  return Math.hypot(a, b) < 0.035 || L < 0.22 || L > 0.95;
}

async function lego() {
  const html = await fetch('https://brickset.com/colours/status-Current', { headers: UA }).then((r) => r.text());
  const rows = [];
  for (const block of html.split("<article class='set'>").slice(1)) {
    const name = /title="([^"]+)"/.exec(block)?.[1];
    const rgb = /background-color:rgb\((\d+),\s*(\d+),\s*(\d+)\)/.exec(block);
    // Solid only: a transparent, chrome, pearl or glitter piece is a surface,
    // and one flat hex says nothing useful about it.
    const solid = /\/colours\/type-Solid'/.test(block);
    if (!name || !rgb || !solid) continue;
    const hex = `#${hex2(rgb[1])}${hex2(rgb[2])}${hex2(rgb[3])}`;
    if (isNeutral(hex)) continue;
    if (rows.some((r) => r.name === name)) continue;
    rows.push({ name, hex });
  }
  rows.sort((a, b) => a.name.localeCompare(b.name));
  return rows;
}

async function copic() {
  const all = await fetch('https://raw.githubusercontent.com/meodai/copic-colors/main/colors.json').then((r) => r.json());
  return all
    .filter((c) => c.extractedColor && c.number)
    .map((c) => ({ name: c.name, code: String(c.number), hex: c.extractedColor.toLowerCase() }))
    .sort((a, b) => a.code.localeCompare(b.code, undefined, { numeric: true }));
}

const [legoRows, copicRows] = await Promise.all([lego(), copic()]);

writeFileSync(
  'apps/theme-editor/src/palette/legoColors.ts',
  `// GENERATED by apps/theme-editor/scripts/gen-brand-colors.mjs
// Source: https://brickset.com/colours/status-Current

/** One LEGO colour: Brickset's name and the value it publishes. */
export interface LegoColor {
  readonly name: string;
  readonly hex: string;
}

/**
 * LEGO colours currently in production, solid and opaque, neutrals excluded.
 *
 * Brickset is the source because it carries the one field LDraw's LDConfig
 * does not: production status. LDConfig would put Fabuland Orange and Maersk
 * Blue in here beside Coral and Dark Azure with nothing to tell them apart.
 */
export const LEGO_COLORS: readonly LegoColor[] = [
${legoRows.map((r) => `  { name: ${JSON.stringify(r.name)}, hex: '${r.hex}' },`).join('\n')}
];
`,
);

writeFileSync(
  'apps/theme-editor/src/palette/copicColors.ts',
  `// GENERATED by apps/theme-editor/scripts/gen-brand-colors.mjs
// Source: https://github.com/meodai/copic-colors (MIT), sampled from copic.jp

/** One Copic marker: its code, its name, and the colour of its swatch. */
export interface CopicColor {
  readonly name: string;
  readonly code: string;
  readonly hex: string;
}

/**
 * The Copic range.
 *
 * Values are the colour sampled from each marker's swatch image on copic.jp,
 * not the tidied hex that dataset also carries — a marker's colour is a
 * measurement, and the sample is the closer account of it. The grays are kept:
 * the N, C, W and T families are a deliberate part of the system rather than
 * the accident that a LEGO gray is.
 */
export const COPIC_COLORS: readonly CopicColor[] = [
${copicRows.map((r) => `  { name: ${JSON.stringify(r.name)}, code: ${JSON.stringify(r.code)}, hex: '${r.hex}' },`).join('\n')}
];
`,
);
