/**
 * Generate the LEGO swatch set from LDraw's colour definitions.
 *
 * Values are read from LDConfig.ldr rather than copied, so they cannot drift
 * from the library. Run with the path to a LDraw install:
 *
 *   node apps/theme-editor/scripts/gen-lego-colors.mjs ~/src/brick-icons/vendor/ldraw/LDConfig.ldr
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const src = process.argv[2];
if (!src) {
  console.error('usage: gen-lego-colors.mjs <path to LDConfig.ldr>');
  process.exit(1);
}

const LINE = /^0 !COLOUR\s+(\S+)\s+CODE\s+(\d+)\s+VALUE\s+(#[0-9A-Fa-f]{6})\s+EDGE\s+\S+(.*)$/;
// Anything with a finish keyword is not a flat colour: a chrome or a pearl is a
// surface, and a swatch of its base hex says nothing useful about it.
const FINISH = /(ALPHA|MATERIAL|CHROME|PEARLESCENT|RUBBER|MATTE_METALLIC|METAL|LUMINANCE)/;

/** sRGB hex to OKLab, so "how colourful is this" is one number. */
function oklab(hex) {
  const [r, g, b] = [1, 3, 5]
    .map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((u) => (u <= 0.04045 ? u / 12.92 : ((u + 0.055) / 1.055) ** 2.4));
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return [
    0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  ];
}

/**
 * Near-neutral, by chroma rather than by channel spread.
 *
 * Spread gets this wrong at the ends: LDraw's Black is #1b2a34, a blue-black
 * whose channels differ by 25 while its chroma is under 0.02. A palette wants
 * hues; the neutrals are the theme's own ramp's job, not a categorical set's.
 */
function isNeutral(hex) {
  const [L, a, b] = oklab(hex);
  return Math.hypot(a, b) < 0.035 || L < 0.22 || L > 0.95;
}

const rows = [];
for (const line of readFileSync(src, 'utf8').split('\n')) {
  const m = LINE.exec(line.trim());
  if (!m) continue;
  const [, name, code, value, rest] = m;
  if (FINISH.test(rest)) continue;
  const hex = value.toLowerCase();
  if (isNeutral(hex)) continue;
  rows.push({ name: name.replace(/_/g, ' '), code: Number(code), hex });
}
rows.sort((a, b) => a.code - b.code);

const out = resolve(process.argv[3] ?? 'apps/theme-editor/src/palette/legoColors.ts');
writeFileSync(
  out,
  `// GENERATED by apps/theme-editor/scripts/gen-lego-colors.mjs from LDraw's LDConfig.ldr.
// Do not edit; re-run the script against a newer LDraw release instead.

/** One LDraw solid colour: LEGO's own number and name, and the flat value. */
export interface LegoColor {
  readonly name: string;
  readonly code: number;
  readonly hex: string;
}

/**
 * LDraw's solid colours — finishes (transparent, chrome, pearl, rubber,
 * metallic, glow) are excluded, because a swatch of a surface's base hex says
 * nothing useful about the surface.
 *
 * Solid, opaque and chromatic: finishes and every near-neutral are dropped.
 *
 * What this is NOT is LEGO's current production range. LDConfig carries no field
 * for what is still made, so Fabuland Orange and Maersk Blue sit in here beside
 * Coral and Dark Azure. Narrowing it needs a by-name list from someone who
 * follows the range; nothing in the library decides it.
 */
export const LEGO_COLORS: readonly LegoColor[] = [
${rows.map((r) => `  { name: ${JSON.stringify(r.name)}, code: ${r.code}, hex: '${r.hex}' },`).join('\n')}
];
`,
);
console.log(`${rows.length} solid colours -> ${out}`);
