/**
 * Writes `packages/core/src/import-shims/engine.ts`, the `@weasel-js/core/engine`
 * entry: every export of core's main entry declared in an engine file
 * (`engineFiles` in check-engine-boundary.mjs), plus the actions, tools and
 * hooks in `HOST` that a host of any dimension binds. Each is re-exported by
 * name from its declaring module, so the entry's import graph is those modules'.
 *
 *   node scripts/gen-engine-entry.mjs           rewrite the entry
 *   node scripts/gen-engine-entry.mjs --check   fail when it is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ENTRY, SRC, engineFiles } from './check-engine-boundary.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ts = createRequire(join(ROOT, 'package.json'))('typescript');
const OUT = join(SRC, ENTRY);

/** Exports outside the engine files a host binds: each must load no 2D code, which the check verifies. */
export const HOST = [
  'moveAction', 'insertAction', 'areaSelectAction', 'createInsertOp',
  'useSelectToolWith', 'selectionMoveContribution', 'useGroupEntryContribution',
  'useActionSet', 'useStandardDeps', 'StandardDeps', 'ENGINE_STANDARD_ACTIONS',
  'createPoseFeed', 'FeedDelta', 'createEnteredGroupScope', 'useEnteredGroup',
  'documentOf', 'scenePoseFrame', 'GesturePreviewSource',
  'WeaselProvider', 'IconRegistryProvider', 'CANVAS_CONTEXT_ATTRIBUTES', 'watchDevicePixelRatio',
];

const HEADER = `// \`@weasel-js/core/engine\` — the half of core a host of any dimension uses: the scene, selection,
// snapping, aim and the dep contract, and the actions and tools such a host binds. Nothing here loads
// the 2D stack (renderer, text, font, stroke, text-dom, svg); \`npm run check:engine-boundary\` fails
// when something does.
//
// Named, from leaf modules, for the reasons \`math.ts\` gives. Generated by
// \`node scripts/gen-engine-entry.mjs\` from core's main entry; do not edit by hand.
`;

function generate() {
  const engine = engineFiles();
  const config = ts.getParsedCommandLineOfConfigFile(join(SRC, '../tsconfig.json'), {}, { ...ts.sys, onUnRecoverableConfigFileDiagnostic: () => {} });
  const program = ts.createProgram([join(SRC, 'index.ts')], { ...config.options, noEmit: true });
  const checker = program.getTypeChecker();
  const main = checker.getSymbolAtLocation(program.getSourceFile(join(SRC, 'index.ts')));
  const byModule = new Map();
  const missing = new Set(HOST);
  for (const sym of checker.getExportsOfModule(main)) {
    const target = sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym;
    const decl = target.declarations?.[0];
    if (!decl) continue;
    const file = resolve(decl.getSourceFile().fileName);
    if (!engine.has(file) && !HOST.includes(sym.name)) continue;
    if (!file.startsWith(SRC)) continue;
    missing.delete(sym.name);
    const own = String(target.escapedName);
    const spec = own === sym.name ? sym.name : `${own} as ${sym.name}`;
    const mod = relative(dirname(OUT), file).replace(/\.tsx?$/, '').replace(/^(?!\.)/, './');
    if (!byModule.has(mod)) byModule.set(mod, { values: [], types: [] });
    byModule.get(mod)[target.flags & ts.SymbolFlags.Value ? 'values' : 'types'].push(spec);
  }
  if (missing.size) throw new Error(`gen-engine-entry: HOST names no export of core's main entry: ${[...missing].join(', ')}`);
  let text = HEADER;
  for (const [mod, { values, types }] of [...byModule].sort(([a], [b]) => a.localeCompare(b))) {
    if (values.length) text += `export { ${values.sort().join(', ')} } from '${mod}';\n`;
    if (types.length) text += `export type { ${types.sort().join(', ')} } from '${mod}';\n`;
  }
  return text;
}

const text = generate();
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch {}
  if (current !== text) {
    console.error(`[engine-entry] ${relative(ROOT, OUT)} is out of date; run node scripts/gen-engine-entry.mjs`);
    process.exit(1);
  }
  console.log('[engine-entry] up to date.');
} else {
  writeFileSync(OUT, text);
  console.log(`[engine-entry] wrote ${relative(ROOT, OUT)}.`);
}
