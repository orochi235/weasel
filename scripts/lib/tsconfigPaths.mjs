/**
 * The root tsconfig's `paths` and core's, from the same `exports` maps the
 * dev aliases come from, so `tsc` resolves a specifier exactly where vite
 * does and refuses the ones vite refuses.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { APP_SOURCES, TESTING, workspaceEntries } from './packageEntries.mjs';

/** Bare top-level paths into core's source, as `scripts/vite-aliases.ts` has them. */
const KIT_DIRS = ['core', 'domains', 'affordances', 'interactions', 'tools', 'canvas', 'debug'];

const OPEN = '    "paths": {\n';
const CLOSE = '\n    }';
const NOTE = '      // Generated by `npm run gen:tsconfig-paths` from every package\'s `exports`; do not edit.\n';

/**
 * @param {string} repoRoot the directory containing `packages/`
 * @returns {Record<string, string[]>} every importable specifier to its source, relative to `repoRoot`
 */
export function tsconfigPaths(repoRoot) {
  /** @type {Record<string, string[]>} */
  const paths = {};
  for (const { dir, name, entries } of workspaceEntries(repoRoot)) {
    const at = (file) => `./${relative(repoRoot, join(dir, file))}`;
    for (const entry of entries) {
      if (entry.source) paths[entry.specifier] = [at(entry.source)];
    }
    if (existsSync(join(dir, 'src', TESTING))) paths[`${name}/${TESTING}/*`] = [at(`src/${TESTING}/*`)];
  }
  for (const dir of KIT_DIRS) paths[`${dir}/*`] = [`./packages/core/src/${dir}/*`];
  for (const [alias, dir] of Object.entries(APP_SOURCES)) paths[`${alias}/*`] = [`./${dir}/*`];
  return paths;
}

/**
 * @param {string} repoRoot the directory containing `packages/`
 * @returns {Record<string, string[]>} `packages/core/tsconfig.json`'s `paths`: the root's, relative to core.
 *   `tsup` reads that file for core's declaration build and resolves inherited `paths` against core's
 *   directory, so core cannot inherit the root's.
 */
export function coreTsconfigPaths(repoRoot) {
  const coreDir = join(repoRoot, 'packages', 'core');
  /** @type {Record<string, string[]>} */
  const paths = {};
  for (const [specifier, [target]] of Object.entries(tsconfigPaths(repoRoot))) {
    const local = relative(coreDir, join(repoRoot, target));
    paths[specifier] = [local.startsWith('.') ? local : `./${local}`];
  }
  return paths;
}

/** `source`, a tsconfig's text, with its `paths` block replaced by `paths`. */
export function withPaths(source, paths) {
  const start = source.indexOf(OPEN);
  const end = source.indexOf(CLOSE, start);
  if (start < 0 || end < 0) throw new Error('tsconfig has no "paths" block to replace');
  const lines = Object.entries(paths).map(([key, value]) => `      ${JSON.stringify(key)}: ${JSON.stringify(value)}`);
  return source.slice(0, start) + OPEN + NOTE + lines.join(',\n') + source.slice(end);
}

/** Rewrite the `paths` of the root tsconfig and of core's. Returns the files that changed, relative to `repoRoot`. */
export function writeTsconfigPaths(repoRoot) {
  const files = { 'tsconfig.json': tsconfigPaths(repoRoot), 'packages/core/tsconfig.json': coreTsconfigPaths(repoRoot) };
  const changed = [];
  for (const [file, paths] of Object.entries(files)) {
    const before = readFileSync(join(repoRoot, file), 'utf8');
    const after = withPaths(before, paths);
    if (after === before) continue;
    writeFileSync(join(repoRoot, file), after);
    changed.push(file);
  }
  return changed;
}
