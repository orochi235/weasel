/**
 * The root tsconfig's `paths`, from the same `exports` maps the dev aliases
 * come from, so `tsc` resolves a specifier exactly where vite does and
 * refuses the ones vite refuses.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { TESTING, workspaceEntries } from './packageEntries.mjs';

/** Bare top-level paths into core's source, as `scripts/vite-aliases.ts` has them. */
const KIT_DIRS = ['core', 'features', 'affordances', 'interactions', 'tools', 'canvas', 'debug'];

const OPEN = '    "paths": {\n';
const CLOSE = '\n    }';
const NOTE = '      // Generated by `npm run gen:tsconfig-paths` from every package\'s `exports`; do not edit.\n';

/**
 * @param {string} repoRoot the directory containing `packages/`
 * @returns {Record<string, string[]>} every importable specifier to its source, relative to `repoRoot`
 */
export function tsconfigPaths(repoRoot) {
  /** @type {Record<string, string[]>} */
  const paths = {};
  for (const { dir, name, entries } of workspaceEntries(repoRoot)) {
    const at = (file) => `./${relative(repoRoot, join(dir, file))}`;
    for (const entry of entries) {
      if (entry.source) paths[entry.specifier] = [at(entry.source)];
    }
    if (existsSync(join(dir, 'src', TESTING))) paths[`${name}/${TESTING}/*`] = [at(`src/${TESTING}/*`)];
  }
  for (const dir of KIT_DIRS) paths[`${dir}/*`] = [`./packages/core/src/${dir}/*`];
  return paths;
}

/** `source`, a tsconfig's text, with its `paths` block replaced by `paths`. */
export function withPaths(source, paths) {
  const start = source.indexOf(OPEN);
  const end = source.indexOf(CLOSE, start);
  if (start < 0 || end < 0) throw new Error('tsconfig has no "paths" block to replace');
  const lines = Object.entries(paths).map(([key, value]) => `      ${JSON.stringify(key)}: ${JSON.stringify(value)}`);
  return source.slice(0, start) + OPEN + NOTE + lines.join(',\n') + source.slice(end);
}

/** Rewrite `<repoRoot>/tsconfig.json`'s `paths`. Returns whether the file changed. */
export function writeTsconfigPaths(repoRoot) {
  const file = join(repoRoot, 'tsconfig.json');
  const before = readFileSync(file, 'utf8');
  const after = withPaths(before, tsconfigPaths(repoRoot));
  if (after !== before) writeFileSync(file, after);
  return after !== before;
}
