// Bundles the voice processor into src/worklet/voiceProcessor.gen.ts as source text.
//
//   node packages/audio/scripts/gen-worklet.mjs           write it
//   node packages/audio/scripts/gen-worklet.mjs --check   fail if it is stale
//
// An AudioWorkletGlobalScope cannot import the package, so the processor has to
// reach `audioWorklet.addModule` as one self-contained script. A string checked
// into source reaches it the same way from vite, vitest and the published dist,
// where a build plugin or virtual module would need one path for each.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const entry = fileURLToPath(new URL('../src/worklet/voiceProcessor.ts', import.meta.url));
const out = fileURLToPath(new URL('../src/worklet/voiceProcessor.gen.ts', import.meta.url));

const result = await build({
  entryPoints: [entry],
  // Its path comments are relative to this, so the output is the same from any cwd.
  absWorkingDir: fileURLToPath(new URL('../src', import.meta.url)),
  bundle: true,
  write: false,
  format: 'iife',
  target: 'es2022',
  platform: 'browser',
  legalComments: 'none',
  charset: 'utf8',
});
const code = result.outputFiles[0].text;

const text = `// Generated by packages/audio/scripts/gen-worklet.mjs from voiceProcessor.ts and what it
// imports. Do not edit: run \`npm run gen:audio-worklet\`; \`npm run check:audio-worklet\` fails while it is stale.

/** The voice processor as one script, for \`audioWorklet.addModule\`. */
export const voiceProcessorSource: string = ${JSON.stringify(code)};
`;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (current !== text) {
    console.error('[audio-worklet] src/worklet/voiceProcessor.gen.ts is stale: run `npm run gen:audio-worklet`.');
    process.exit(1);
  }
  console.log('[audio-worklet] OK — the generated processor matches its source.');
} else {
  writeFileSync(out, text);
  console.log(`[audio-worklet] wrote ${out} (${code.length} chars)`);
}
