// Emits src/icons/generated/paths.ts, src/icons/generated/fills.ts and src/icons/generated/groups.ts from the glyph definitions in ./icons/.
//
// The definitions compute their own terminus geometry (see icons/base.mjs), so
// the checked-in paths.ts holds resolved literals and ships no math. Re-run
// after touching anything under scripts/icons/:
//
//   node packages/ui/scripts/gen-icons.mjs
//
// Proof a change before committing it — CLAUDE.md ("Drawing icons") requires
// inspecting at 240-320px, not at chrome size.

import { writeFileSync } from 'node:fs';
import { BASE } from './icons/base.mjs';
import { ARROWS, HIERARCHY } from './icons/arrows.mjs';
import { CAMERA } from './icons/camera.mjs';
import { CHROME } from './icons/chrome.mjs';
import { FILES } from './icons/files.mjs';
import { SIZE } from './icons/size.mjs';
import { ACTIONS } from './icons/actions.mjs';
import { INSTRUMENT, PLAYBACK, STATUS } from './icons/state.mjs';
import { PAGING } from './icons/paging.mjs';
import { PAINT } from './icons/paint.mjs';
import { LAYOUT } from './icons/layout.mjs';
import { FORM } from './icons/form.mjs';
import { REPO } from './icons/repo.mjs';
import { ARCS } from './icons/arcs.mjs';
import { CURVES } from './icons/curves.mjs';
import { SHAPES } from './icons/shapes.mjs';
import { SOLIDS } from './icons/solids.mjs';
import { PARAGRAPH, TEXT } from './icons/text.mjs';
import { STATUSES } from './icons/status.mjs';
import { VARIANTS } from './icons/variants.mjs';
import { MARKS } from './icons/marks.mjs';
import { KEYS } from './icons/keys.mjs';

const RENAME = { zoom: 'zoomIn' };

// The group whose glyphs `<Icon mark>` takes.
const MARK_GROUP = 'Marks';

const GROUPS = [
  ['View and lifecycle', BASE],
  ['Actions', ACTIONS],
  ['Character styling', TEXT],
  ['Paragraph alignment', PARAGRAPH],
  ['Playback', PLAYBACK],
  ['Paging', PAGING],
  ['Arrows', ARROWS],
  ['Key legends', KEYS],
  ['Hierarchy', HIERARCHY],
  ['Size', SIZE],
  ['Camera moves', CAMERA],
  ['App chrome', CHROME],
  ['Files', FILES],
  ['State', STATUS],
  ['Badge status', STATUSES],
  ['Component variants', VARIANTS],
  ['Instrument', INSTRUMENT],
  ['Stroke cap, join, align and dash', PAINT],
  ['Workspace layout', LAYOUT],
  ['Settings form', FORM],
  ['Repository views', REPO],
  [MARK_GROUP, MARKS],
  ['Arc profiles', ARCS],
  ['Curves', CURVES],
  ['Shapes', SHAPES],
  ['Platonic solids', SOLIDS],
];

// A digit has no upper case, so `star-4` has to drop the dash rather than try to
// capitalize it — an emitted `shapeStar-4` is not a valid object key.
const camel = (k) => k.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
// Join with a space (attributes split across lines must stay separated),
// then close the gaps between adjacent elements.
const clean = (body) =>
  body
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .join(' ')
    .replace(/>\s+</g, '><');

// A name collision used to be skipped in silence, so a new glyph could vanish
// into an existing one's key with the generator reporting success. Identical
// bodies are the deliberate alias (`export` is `BASE.export`); different ones are
// someone's drawing being dropped.
// A drawn glyph arrives as a string of markup; a plotted one arrives as
// { d, width, inner, fill, rule, join } and is turned into markup here, so the definitions stay
// geometry and the emitter stays the only place that writes elements.
const element = (glyph) =>
  typeof glyph === 'string'
    ? clean(glyph)
    : `<path d="${glyph.d}"${glyph.join ? ` stroke-linejoin="${glyph.join}"` : ''}` +
      `${glyph.width ? ` stroke-width="${glyph.width}"` : ''}/>` +
      (glyph.inner ? `<path d="${glyph.inner.d}" stroke-width="${glyph.inner.width}"/>` : '');
const fillElement = (glyph) =>
  typeof glyph === 'string' || !glyph.fill
    ? null
    : `<path d="${glyph.fill}" fill="currentColor" stroke="none"` +
      `${glyph.rule ? ` fill-rule="${glyph.rule}"` : ''}/>`;

// Glyphs a core action or tool ships as its default icon. Core cannot depend on
// this package, so their markup is emitted into core and `ICON_PATHS` points at it.
const CORE_GLYPHS = ['delete', 'undo', 'redo', 'measure', 'tune'];
const CORE_FILE = '../../core/src/interactions/actions/defaults/icons/actionGlyphs.ts';

const seen = new Map();
const fills = new Map();
const members = [];
let out = `// GENERATED by scripts/gen-icons.mjs — do not edit by hand.
// Every glyph is a 20x20 viewBox drawn in currentColor at stroke-width 1.5.

import { ACTION_GLYPHS } from '@weasel-js/core';

/** The SVG body of every glyph, by name — what \`<Icon name>\` draws. */
export const ICON_PATHS = {
`;

for (const [label, set] of GROUPS) {
  out += `\n  // ${label}\n`;
  const names = [];
  members.push([label, names]);
  for (const [rawKey, body] of Object.entries(set)) {
    if (rawKey.startsWith('_') || rawKey === 'attrs') continue;
    const key = camel(RENAME[rawKey] ?? rawKey);
    const drawing = element(body);
    const prior = seen.get(key);
    if (prior !== undefined) {
      if (prior === drawing) continue;
      throw new Error(`icon "${key}" is drawn twice, differently — rename one`);
    }
    if (label === MARK_GROUP && drawing.includes('stroke-width')) {
      throw new Error(`mark "${key}" sets a stroke-width, which the slot would scale down with it`);
    }
    seen.set(key, drawing);
    names.push(key);
    const fill = fillElement(body);
    if (fill) fills.set(key, fill);
    out += CORE_GLYPHS.includes(key)
      ? `  ${key}: ACTION_GLYPHS.${key},\n`
      : `  ${key}: \`${drawing}\`,\n`;
  }
}

out += `} as const;

/** Every glyph name in the set. */
export type IconName = keyof typeof ICON_PATHS;
`;

let shades = `// GENERATED by scripts/gen-icons.mjs — do not edit by hand.

/** The region a glyph encloses, for \`<Icon filled>\`. A shape fills its own
 *  outline; a plotted curve fills down to the frame's baseline, reaching the outer
 *  edge of the stroke rather than stopping at the path's own endpoint. Only the
 *  glyphs where an enclosed region means something have an entry. */
export const ICON_FILLS = {
`;
for (const [key, fill] of fills) shades += `  ${key}: \`${fill}\`,\n`;
shades += `} as const;

/** The glyphs \`<Icon filled>\` can shade. */
export type FillableIconName = keyof typeof ICON_FILLS;
`;

let groups = `// GENERATED by scripts/gen-icons.mjs — do not edit by hand.

import type { IconName } from './paths';

/** Every glyph in \`ICON_PATHS\`, once, sorted into the families it was drawn in. */
export const ICON_GROUPS: readonly { label: string; names: readonly IconName[] }[] = [
`;
for (const [label, names] of members) {
  groups += `  { label: '${label}', names: [\n${names.map((n) => `    '${n}',\n`).join('')}  ] },\n`;
}
groups += `];
`;

groups += `
/** The glyphs drawn to be read small, which \`<Icon mark>\` sets in a corner of another. */
export const MARK_ICONS = [
${members.find(([label]) => label === MARK_GROUP)[1].map((n) => `  '${n}',\n`).join('')}] as const satisfies readonly IconName[];

/** A glyph \`<Icon mark>\` takes. */
export type MarkIconName = (typeof MARK_ICONS)[number];
`;

for (const key of CORE_GLYPHS) {
  if (!seen.has(key)) throw new Error(`core glyph "${key}" is not drawn`);
  if (fills.has(key)) throw new Error(`core glyph "${key}" has a fill core does not render`);
}
const core = `// GENERATED by packages/ui/scripts/gen-icons.mjs — do not edit by hand.
// Drawn in packages/ui/scripts/icons/; @weasel-js/ui's ICON_PATHS points here.

/**
 * SVG bodies of the glyphs core's actions and tools ship as their icons —
 * undo, redo, delete, the measure tool's ruler, and the settings sliders: 20x20 viewBox, stroked
 * in currentColor at stroke-width 1.5 with round caps and joins.
 * \`<Icon name="undo" />\` in \`@weasel-js/ui\` draws the same one.
 */
export const ACTION_GLYPHS = {
${CORE_GLYPHS.map((k) => `  ${k}: \`${seen.get(k)}\`,\n`).join('')}} as const;
`;

writeFileSync(new URL('../src/icons/generated/paths.ts', import.meta.url), out);
writeFileSync(new URL('../src/icons/generated/fills.ts', import.meta.url), shades);
writeFileSync(new URL('../src/icons/generated/groups.ts', import.meta.url), groups);
writeFileSync(new URL(CORE_FILE, import.meta.url), core);
console.log(`wrote ${seen.size} glyphs to src/icons/generated/paths.ts and ${fills.size} fills to src/icons/generated/fills.ts`);
