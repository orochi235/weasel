export const HEADER = '// GENERATED by packages/icons/scripts/gen-icons.mjs — do not edit by hand.\n';

const pascal = (ns) => ns.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase());

/** `@weasel-js/icons` draws glyphs too, and a package importing its own name imports itself. */
const SELF = '@weasel-js/icons';
const isSelf = (table) => table.owner === SELF;

export function emitTableModule(table) {
  return `${HEADER}
import type { IconTable } from '${isSelf(table) ? './table' : SELF}';
import data from './icons.table.json';

/** Every glyph this package ships, under the \`${table.namespace}\` namespace. */
export const icons: IconTable = data;
`;
}

export function emitGen(table, groups) {
  const names = Object.keys(table.icons);
  const P = pascal(table.namespace);
  const keys = names.map((n) => `    '${table.namespace}:${n}': true;`).join('\n');
  // The barrel declares IconName, so its own names extend it rather than augment it.
  const declared = isSelf(table)
    ? `/** This package's qualified names, which \`IconName\` extends. */
export interface ${P}IconNames {
${keys.replaceAll('\n    ', '\n  ').replace(/^ {4}/, '  ')}
}`
    : `declare module '${SELF}' {
  interface IconName {
${keys}
  }
}`;
  return `${HEADER}
import { scopedIcon } from '${isSelf(table) ? './names' : SELF}';

/** A glyph this package draws, by its bare name. */
export type ${P}IconName =
${names.map((n) => `  | '${n}'`).join('\n')};

/** This package's \`icon()\`: a bare name means \`${table.namespace}:<name>\`. */
export const icon = scopedIcon<${P}IconName>('${table.namespace}');

/** This package's glyphs, in the families they were drawn in. */
export const ICON_GROUPS: readonly { label: string; names: readonly ${P}IconName[] }[] = ${JSON.stringify(groups, null, 2)};

${declared}
`;
}

/** The icon() of a root that draws nothing: every name it writes is qualified, so the build sees each one. */
export function emitConsumerGen(namespace) {
  return `${HEADER}
import { scopedIcon } from '${SELF}';

/** This package draws no glyphs of its own, so every name it writes is qualified: \`icon('ui:close')\`. */
export const icon = scopedIcon<never>('${namespace}');
`;
}
