// Writes ui's pre-registry outputs (src/icons/generated/{paths,fills,groups}.ts and core's
// actionGlyphs.ts) from ui's built table, until the registry replaces them. Task 6 deletes this file.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const HEADER = '// GENERATED by packages/icons/scripts/gen-icons.mjs — do not edit by hand.\n';

// Glyphs a core action or tool ships as its default icon. Core cannot depend on
// ui, so their markup is emitted into core and `ICON_PATHS` points at it.
const CORE_GLYPHS = ['delete', 'undo', 'redo', 'measure', 'tune'];
const CORE_FILE = 'packages/core/src/interactions/actions/defaults/icons/actionGlyphs.ts';

// Where each core glyph sat in ui's old groups: after which glyph of which group.
const LEGACY_SLOT = {
  delete: ['Actions', 'remove'],
  undo: ['Actions', 'sort'],
  redo: ['Actions', 'undo'],
  tune: ['Instrument', 'chevron'],
  measure: ['Instrument', 'snap'],
};

/** ui's table with the core glyphs put back where its old outputs had them. */
function withCoreGlyphs(uiTable, coreTable) {
  const icons = { ...uiTable.icons };
  const groups = uiTable.groups.map(({ label, names }) => ({ label, names: [...names] }));
  for (const key of CORE_GLYPHS) {
    const glyph = coreTable.icons[key];
    if (!glyph) throw new Error(`core glyph "${key}" is not drawn`);
    if (glyph.fill) throw new Error(`core glyph "${key}" has a fill core does not render`);
    const [label, after] = LEGACY_SLOT[key];
    const names = groups.find((g) => g.label === label).names;
    names.splice(names.indexOf(after) + 1, 0, key);
    icons[key] = glyph;
  }
  return { ...uiTable, icons, groups };
}

function emitPaths(table) {
  let out = `${HEADER}// Every glyph is a 20x20 viewBox drawn in currentColor at stroke-width 1.5.

import { ACTION_GLYPHS } from '@weasel-js/core';

/** The SVG body of every glyph, by name — what \`<Icon name>\` draws. */
export const ICON_PATHS = {
`;
  for (const { label, names } of table.groups) {
    out += `\n  // ${label}\n`;
    for (const key of names) {
      out += CORE_GLYPHS.includes(key)
        ? `  ${key}: ACTION_GLYPHS.${key},\n`
        : `  ${key}: \`${table.icons[key].body}\`,\n`;
    }
  }
  return `${out}} as const;

/** Every glyph name in the set. */
export type IconName = keyof typeof ICON_PATHS;
`;
}

function emitFills(table) {
  let out = `${HEADER}
/** The region a glyph encloses, for \`<Icon filled>\`. A shape fills its own
 *  outline; a plotted curve fills down to the frame's baseline, reaching the outer
 *  edge of the stroke rather than stopping at the path's own endpoint. Only the
 *  glyphs where an enclosed region means something have an entry. */
export const ICON_FILLS = {
`;
  for (const [key, glyph] of Object.entries(table.icons)) if (glyph.fill) out += `  ${key}: \`${glyph.fill}\`,\n`;
  return `${out}} as const;

/** The glyphs \`<Icon filled>\` can shade. */
export type FillableIconName = keyof typeof ICON_FILLS;
`;
}

function emitGroups(table, markGroup) {
  let out = `${HEADER}
import type { IconName } from './paths';

/** Every glyph in \`ICON_PATHS\`, once, sorted into the families it was drawn in. */
export const ICON_GROUPS: readonly { label: string; names: readonly IconName[] }[] = [
`;
  for (const { label, names } of table.groups) {
    out += `  { label: '${label}', names: [\n${names.map((n) => `    '${n}',\n`).join('')}  ] },\n`;
  }
  const marks = table.groups.find(({ label }) => label === markGroup).names;
  return `${out}];

/** The glyphs drawn to be read small, which \`<Icon mark>\` sets in a corner of another. */
export const MARK_ICONS = [
${marks.map((n) => `  '${n}',\n`).join('')}] as const satisfies readonly IconName[];

/** A glyph \`<Icon mark>\` takes. */
export type MarkIconName = (typeof MARK_ICONS)[number];
`;
}

function emitCore(source) {
  return `${HEADER}// Drawn in packages/ui/icons/; @weasel-js/ui's ICON_PATHS points here.

/**
 * @experimental
 * SVG bodies of the glyphs core's actions and tools ship as their icons —
 * undo, redo, delete, the measure tool's ruler, and the settings sliders: 20x20 viewBox, stroked
 * in currentColor at stroke-width 1.5 with round caps and joins.
 * \`<Icon name="undo" />\` in \`@weasel-js/ui\` draws the same one.
 */
export const ACTION_GLYPHS = {
${CORE_GLYPHS.map((k) => `  ${k}: \`${source[k].body}\`,\n`).join('')}} as const;
`;
}

/** `table` is ui's built table plus its `groups`; `coreTable` is core's. */
export function writeLegacyUi({ repo, root, table: uiTable, coreTable, markGroup }) {
  const table = withCoreGlyphs(uiTable, coreTable);
  const dir = join(root, 'src/icons/generated');
  writeFileSync(join(dir, 'paths.ts'), emitPaths(table));
  writeFileSync(join(dir, 'fills.ts'), emitFills(table));
  writeFileSync(join(dir, 'groups.ts'), emitGroups(table, markGroup));
  writeFileSync(join(repo, CORE_FILE), emitCore(coreTable.icons));
}
