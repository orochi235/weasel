#!/usr/bin/env node
/**
 * Turn a vitest benchmark JSON report into the committed Markdown baseline.
 *
 * Usage:
 *   node tests/perf/bench-report.mjs [--in <json>] [--out <md>]
 *   node tests/perf/bench-report.mjs --merge <json> [--in <json>] [--out <md>]
 *
 * Defaults read `tests/perf/bench/baseline.json` and write
 * `tests/perf/bench/BASELINE.md`. Prints one line per benchmark as it
 * goes, so the step is legible in a terminal rather than silent.
 *
 * `--merge` takes a report of some bench files (`npm run perf:bench -- --raw`),
 * replaces those files' entries in `--in` and their sections in `--out`, and
 * leaves the header and every other section alone. The header's note on what
 * was re-measured is hand-written.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';
import os from 'node:os';
import { readBenchReport } from './lib/vitest-bench.ts';
import { mergeReports, ms, renderSections, spliceSections } from './lib/benchReport.ts';

const args = process.argv.slice(2);
const argOf = (flag, fallback) => {
  const i = args.indexOf(flag);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};

const repoRoot = resolve(import.meta.dirname, '../..');
const inPath = resolve(repoRoot, argOf('--in', 'tests/perf/bench/baseline.json'));
const outPath = resolve(repoRoot, argOf('--out', 'tests/perf/bench/BASELINE.md'));

const mergeArg = argOf('--merge', null);
let report = JSON.parse(readFileSync(inPath, 'utf8'));
let mergedSuites = null;
if (mergeArg) {
  const merged = mergeReports(report, JSON.parse(readFileSync(resolve(repoRoot, mergeArg), 'utf8')));
  report = merged.report;
  mergedSuites = new Set(merged.suites);
  writeFileSync(inPath, JSON.stringify(report));
}

const rows = readBenchReport(report).filter((b) => !mergedSuites || mergedSuites.has(b.suite));
rows.forEach((b, i) => {
  console.log(
    `[${i + 1}/${rows.length}] ${b.suite} > ${b.group} :: ${b.name}  median=${ms(b.median)}ms  rme=±${b.rme.toFixed(1)}%`,
  );
});

const sections = renderSections(rows);
if (mergedSuites) {
  writeFileSync(outPath, spliceSections(readFileSync(outPath, 'utf8'), sections));
  console.log(`\nMerged ${[...mergedSuites].join(', ')} into ${relative(repoRoot, inPath)} and ${relative(repoRoot, outPath)}.`);
} else {
  const lines = [];
  lines.push('# Benchmark baseline');
  lines.push('');
  lines.push(
    'Generated by `npm run perf:bench:baseline`. **These are one machine\'s numbers, ' +
    'not a threshold.** They are portable as ratios and curve shapes, not as ' +
    'absolute milliseconds. See `tests/perf/README.md`.',
  );
  lines.push('');
  lines.push('| | |');
  lines.push('|---|---|');
  lines.push(`| Measured | ${new Date().toISOString().slice(0, 10)} |`);
  lines.push(`| CPU | ${os.cpus()[0]?.model ?? 'unknown'} (${os.cpus().length} threads) |`);
  lines.push(`| Arch | ${process.platform}/${process.arch} |`);
  lines.push(`| Node | ${process.version} |`);
  lines.push(`| Memory | ${Math.round(os.totalmem() / 1024 ** 3)} GB |`);
  lines.push('');
  lines.push(
    '`median` is the number to compare — the mutating and allocation-heavy ' +
    'benchmarks take periodic GC pauses that inflate the mean by an order of ' +
    'magnitude without the code having changed. `rme` is the relative margin ' +
    'of error on the mean; a large one means read the median and ignore the ' +
    'mean entirely.',
  );
  lines.push('');
  for (const section of sections.values()) lines.push(...section);
  writeFileSync(outPath, `${lines.join('\n')}\n`);
  console.log(`\nWrote ${relative(repoRoot, outPath)} (${rows.length} benchmarks).`);
}
